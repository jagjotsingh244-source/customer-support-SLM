"""Render one full tool round trip through Qwen3.5-2B's chat template and mark every part.

The conversation is the agent's own: Nova's system prompt, the six real tool schemas, a customer
question, the assistant's tool call, the real tool result from the local database, and the cue for
the next model pass. The output shows where the tool definitions, the call and the result sit in
the prompt, which special tokens surround each, and what each part costs in tokens.

    uv run --group local-model python notes/tool-call-anatomy/render_round_trip.py > notes/tool-call-anatomy/round_trip.txt

Needs the local database (docker compose up -d) for the tool result.
"""

import json
import re
import sys
from pathlib import Path

from transformers import AutoTokenizer

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from agent import tools_v0  # noqa: E402
from agent.local_client import _for_template  # noqa: E402
from agent.prompts import system_prompt  # noqa: E402
from agent.tools_v1 import TOOLS  # noqa: E402
from config import now  # noqa: E402

MID = "Qwen/Qwen3.5-2B"
DB_URL = "postgresql://nimbus:nimbus@localhost:5433/nimbus"
CUSTOMER, ORDER = 416, 11904          # golden case ord-001: a delayed webcam
QUESTION = f"Where is my order {ORDER}?"

tok = AutoTokenizer.from_pretrained(MID)
session = tools_v0.Session.open(tools_v0.connect(DB_URL), CUSTOMER)
result = tools_v0.get_tracking(session, ORDER)

call = {"id": "call_0", "type": "function",
        "function": {"name": "get_tracking", "arguments": json.dumps({"order_id": ORDER})}}
messages = [
    {"role": "system", "content": system_prompt(now(), session.customer_name)},
    {"role": "user", "content": QUESTION},
    {"role": "assistant", "content": None, "tool_calls": [call]},
    {"role": "tool", "tool_call_id": "call_0", "content": json.dumps(result, default=str, ensure_ascii=False)},
]


def render(msgs, gen=True):
    return tok.apply_chat_template(_for_template(msgs), tools=TOOLS, add_generation_prompt=gen, tokenize=False)


def n_tokens(text):
    return len(tok(text, add_special_tokens=False).input_ids)


# Each prefix of the conversation, rendered on its own: the difference between two prefixes is the
# text the template adds for that message. The first model pass sees `first`; the second sees `full`.
first = render(messages[:2])
after_call = render(messages[:3], gen=False)
full = render(messages)
assert full.startswith(after_call), "the template rewrites earlier turns"

system_end = first.index("<|im_end|>") + len("<|im_end|>\n")
tools_start, tools_end = first.index("# Tools"), first.index("</IMPORTANT>") + len("</IMPORTANT>")
call_start = after_call.rindex("<|im_start|>assistant")
result_start = full.index("<|im_start|>", call_start + 1)
cue_start = full.rindex("<|im_start|>assistant")

parts = [
    ("A. TOOL DEFINITIONS (template text + 6 schemas, inside the system turn)", full[tools_start:tools_end]),
    ("B. NOVA'S SYSTEM PROMPT (after the tools, same system turn)", full[tools_end:system_end]),
    ("C. CUSTOMER MESSAGE", full[system_end:full.index("<|im_start|>assistant")]),
    ("D. THE TOOL CALL (an earlier assistant turn now)", full[call_start:result_start]),
    ("E. THE TOOL RESULT (rendered as a user turn)", full[result_start:cue_start]),
    ("F. CUE FOR THE NEXT MODEL PASS", full[cue_start:]),
]
assert "".join(p[1] for p in parts) == full[tools_start:], "parts must cover the prompt exactly"
assert full[:tools_start] == "<|im_start|>system\n"

print(f"# {MID} chat template, one tool round trip. Customer {CUSTOMER}, order {ORDER}.")
print("# Every character of the second model pass's prompt appears below, in order, split into marked parts.")
print("# Generated by render_round_trip.py; special tokens kept.\n")
print("<|im_start|>system\n", end="")
for title, text in parts:
    print(f"\n{'=' * 12} {title}: {n_tokens(text)} tokens {'=' * 12}")
    shown = text
    if title.startswith("A."):          # the six schemas are long; show one, count all
        lines = shown.split("\n")
        schema_lines = [i for i, line in enumerate(lines) if line.startswith('{"type": "function"')]
        keep = lines[:schema_lines[0] + 1] + [f"... {len(schema_lines) - 1} more schemas, one per line ..."] \
            + lines[schema_lines[-1] + 1:]
        shown = "\n".join(keep)
    print(shown, end="" if shown.endswith("\n") else "\n")

print(f"\n{'=' * 12} SPECIAL TOKENS IN THE PROMPT {'=' * 12}")
specials = re.findall(r"<\|[^|]+\|>|</?(?:tools|tool_call|tool_response|think|IMPORTANT)>", full)
for t in dict.fromkeys(specials):
    ids = tok(t, add_special_tokens=False).input_ids
    kind = "one token" if len(ids) == 1 else f"{len(ids)} ordinary tokens"
    print(f"{t:18s} x{specials.count(t)}  ({kind})")
for t in ["<function=", "<parameter=", "</function>", "</parameter>"]:
    print(f"{t:18s} x{full.count(t)}  ({len(tok(t, add_special_tokens=False).input_ids)} ordinary tokens)")

print(f"\n{'=' * 12} TOKEN COUNTS {'=' * 12}")
print(f"first model pass (system + tools + question + cue): {n_tokens(first)}")
print(f"second model pass (adds the call and the result):   {n_tokens(full)}")
print(f"  of which the tool call: {n_tokens(parts[3][1])}, the tool result: {n_tokens(parts[4][1])}")
print(f"raw JSON of the result alone: {n_tokens(messages[3]['content'])} tokens, {len(messages[3]['content'])} characters")
