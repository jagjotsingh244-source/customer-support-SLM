"""Run Qwen3.5-2B inside the process with Transformers, behind the same call the agent loop makes.

For machines without a vLLM server (e.g. a Mac: Apple GPU through MPS). The loop calls
client.chat.completions.create(...) exactly as it does for vLLM; this client renders the same chat
template with the same tool schemas, generates, and turns the model's tool calls back into
OpenAI-style tool calls the way vLLM's qwen3_coder parser does.

    client = LocalChatClient("Qwen/Qwen3.5-2B")                       # the base model
    client = LocalChatClient("Qwen/Qwen3.5-2B", adapter="<hub id>")   # with a LoRA adapter merged in
    run_turn(client, "Qwen/Qwen3.5-2B", messages, TOOLS, REGISTRY, session)

Matching vLLM on purpose:
- fp16 weights from the Hub, the model's own chat template, thinking off (the template's default).
- Sampling: temperature as given, top_p as given (default 1.0), top_k off unless given, and
  presence_penalty applied to generated tokens only, as vLLM does.
- Stops on <|im_end|> or <|endoftext|> (the repo's config names only the second; see
  notes/generation-experiments).
- Tool calls: <tool_call><function=NAME><parameter=P>value</parameter>...</function></tool_call>.
  Parameter values are converted with the tool's JSON schema (integer, number, boolean, object,
  array); a value that does not convert stays a string, so a malformed call is still visible.
Differences that remain: a different kernel stack (MPS, not CUDA) gives slightly different numbers,
so outputs are not token-for-token identical to vLLM's, and latency here is not serving latency.
"""

import json
import re
import time
from types import SimpleNamespace

import torch
import transformers
from openai.types.chat import ChatCompletion
from transformers import AutoTokenizer, LogitsProcessor, LogitsProcessorList

from agent.chat_template import for_template as _for_template

TOOL_CALL = re.compile(r"<tool_call>\s*<function=([^>\s]+)>(.*?)</function>\s*</tool_call>", re.S)
PARAM = re.compile(r"<parameter=([^>\s]+)>(.*?)</parameter>", re.S)


class PresencePenalty(LogitsProcessor):
    """OpenAI/vLLM presence_penalty: lower every token already generated by a flat amount."""

    def __init__(self, penalty: float, prompt_len: int):
        self.penalty, self.prompt_len = penalty, prompt_len

    def __call__(self, input_ids, scores):
        generated = input_ids[:, self.prompt_len:]
        for row in range(generated.shape[0]):
            seen = torch.unique(generated[row])
            if seen.numel():
                scores[row, seen] -= self.penalty
        return scores


def _convert(value: str, schema: dict | None):
    """A parameter's text -> a typed value, using the tool schema (as vLLM's qwen3_coder parser does)."""
    v = value.strip("\n")
    kind = (schema or {}).get("type")
    try:
        if kind == "integer":
            return int(v.strip())
        if kind == "number":
            return float(v.strip())
        if kind == "boolean":
            return {"true": True, "false": False}[v.strip().lower()]
        if kind in ("object", "array"):
            return json.loads(v)
    except (ValueError, KeyError, json.JSONDecodeError):
        pass
    return v


def parse_tool_calls(text: str, tools: list[dict]) -> tuple[str | None, list[dict]]:
    """Model output -> (text before the first tool call, OpenAI-style tool calls)."""
    props = {t["function"]["name"]: t["function"]["parameters"].get("properties", {}) for t in tools or []}
    calls = []
    for i, m in enumerate(TOOL_CALL.finditer(text)):
        name, body = m.group(1), m.group(2)
        args = {p: _convert(v, props.get(name, {}).get(p)) for p, v in PARAM.findall(body)}
        calls.append({"id": f"call_{i}", "type": "function",
                      "function": {"name": name, "arguments": json.dumps(args, ensure_ascii=False)}})
    content = text.split("<tool_call>")[0].strip() if calls else text.strip()
    return content or None, calls


def attach_adapter(model, adapter: str):
    """Loads a LoRA adapter (Hub id or folder) onto the base and merges it in, so generation runs at base speed.

    Fails if the adapter wraps no layer: an adapter whose layer names do not match this model class would
    otherwise load silently and leave the base model unchanged.
    """
    from peft import PeftModel

    model = PeftModel.from_pretrained(model, adapter)
    wrapped = sum(1 for _, m in model.named_modules() if hasattr(m, "lora_A") and len(m.lora_A) > 0)
    if wrapped == 0:
        raise RuntimeError(f"adapter {adapter} matched no layer of {type(model.base_model.model).__name__}")
    print(f"adapter {adapter}: {wrapped} layers wrapped, merged into the base")
    return model.merge_and_unload().eval()


class LocalChatClient:
    """Exposes client.chat.completions.create(...), the one call agent/loop.py makes."""

    def __init__(self, model_id: str, device: str | None = None, adapter: str | None = None):
        self.device = device or ("mps" if torch.backends.mps.is_available()
                                 else "cuda" if torch.cuda.is_available() else "cpu")
        model_cls = getattr(transformers, "AutoModelForMultimodalLM", None) or transformers.AutoModelForImageTextToText
        self.tok = AutoTokenizer.from_pretrained(model_id)
        self.model = model_cls.from_pretrained(model_id, dtype=torch.float16).to(self.device).eval()
        if adapter:
            self.model = attach_adapter(self.model, adapter)
        self.eos = [self.tok.convert_tokens_to_ids("<|im_end|>"), self.tok.convert_tokens_to_ids("<|endoftext|>")]
        self.model_id = model_id
        self.chat = SimpleNamespace(completions=SimpleNamespace(create=self.create))

    @torch.inference_mode()
    def create(self, *, model, messages, tools, temperature, max_tokens, top_p=1.0,
               presence_penalty=0.0, extra_body=None, **_):
        enc = self.tok.apply_chat_template(_for_template(messages), tools=tools, add_generation_prompt=True,
                                           return_tensors="pt", return_dict=True).to(self.device)
        n_prompt = enc["input_ids"].shape[1]
        top_k = (extra_body or {}).get("top_k") or 0
        processors = LogitsProcessorList([PresencePenalty(presence_penalty, n_prompt)] if presence_penalty else [])
        out = self.model.generate(
            **enc, max_new_tokens=max_tokens, eos_token_id=self.eos, logits_processor=processors,
            do_sample=temperature > 0, temperature=temperature if temperature > 0 else None,
            top_p=top_p, top_k=top_k)[0, n_prompt:]
        ended = len(out) > 0 and int(out[-1]) in self.eos
        text = self.tok.decode(out, skip_special_tokens=False)
        for stop in ("<|im_end|>", "<|endoftext|>"):
            text = text.split(stop)[0]
        content, calls = parse_tool_calls(text, tools)
        n_out = len(out) - (1 if ended else 0)
        return ChatCompletion.model_validate({
            "id": f"local-{time.monotonic_ns()}", "object": "chat.completion", "created": 0, "model": model,
            "usage": {"prompt_tokens": n_prompt, "completion_tokens": n_out, "total_tokens": n_prompt + n_out},
            "choices": [{"index": 0, "finish_reason": "tool_calls" if calls else ("stop" if ended else "length"),
                         "message": {"role": "assistant", "content": content, "tool_calls": calls or None}}]})
